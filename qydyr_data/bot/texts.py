def t(lang: str, key: str, **kw) -> str:
    s = T.get(lang, T["ru"]).get(key) or T["ru"][key]
    return s.format(**kw) if kw else s


def user_lang(code: str | None) -> str:
    code = (code or "").lower()
    return "kk" if code.startswith("kk") else "en" if code.startswith("en") else "ru"


def plural(lang: str, n: int, forms: str) -> str:
    """'место|места|мест' (ru), 'place|places' (en), one form (kk)."""
    f = forms.split("|")
    if len(f) == 3:
        d, h = n % 10, n % 100
        return f[0] if d == 1 and h != 11 else f[1] if 2 <= d <= 4 and not 12 <= h <= 14 else f[2]
    return f[0] if len(f) == 1 or n == 1 else f[1]
